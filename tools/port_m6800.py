"""Generate the standalone 6800 core (emu/src/cpu/m6800/) from MAME's sources in
reference/mame/cpu/m6800 (BSD-3-Clause, commit in reference/MAME-SOURCE.txt).

MAME's text is taken verbatim wherever it can be: the opcode handlers (6800ops.hxx, copied
unchanged), the macros, the flag and cycle tables, the instruction table, and the reset,
interrupt and execute routines. Only the device framework is replaced, by small adapters
with the same names (as the 2650 core does), and the m6802/m6808/nsc8105 variants are left
out. Hand edits belong in this script, not in its output.

  tools/port_m6800.py [reference/mame/cpu/m6800] [emu/src/cpu/m6800]
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'reference', 'mame', 'cpu', 'm6800')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, '..', 'emu', 'src', 'cpu', 'm6800')
cpp = open(os.path.join(src, 'm6800.cpp')).read()
hdr = open(os.path.join(src, 'm6800.h')).read()
ops = open(os.path.join(src, '6800ops.hxx')).read()

def between(text, start, end):
    i = text.index(start)
    j = text.index(end, i)
    return text[i:j]

def function(text, signature):
    """A whole function definition, from its signature to its closing brace at column 0."""
    i = text.index(signature)
    j = text.index('\n}\n', i) + 3
    return text[i:j]

NOTE = """// Generated by tools/port_m6800.py from MAME's src/devices/cpu/m6800 (commit in
// reference/MAME-SOURCE.txt): a standalone port for the Tektronix 8002 emulator. Do not edit:
// change the script. MAME's device framework is replaced by adapters with the same names.
"""
LICENSE = '// license:BSD-3-Clause\n// copyright-holders:Aaron Giles\n'

# the opcode handler declarations of m6800_cpu_device, as MAME's header lists them
decls = re.findall(r'^\tvoid [a-z0-9_]+\(\);$', hdr, re.M)
assert len(decls) > 200, 'opcode declarations not found'

header = LICENSE + NOTE + """#ifndef TEK_CPU_M6800_H
#define TEK_CPU_M6800_H
#include "emu.h"

enum { M6800_IRQ_LINE = 0, INPUT_LINE_NMI = 32 };

class m6800_cpu_device
{
public:
	struct bus_interface {
		virtual ~bus_interface() = default;
		virtual u8 read(u16 a, bool opcode) = 0;   // opcode: the instruction's first byte (an instruction fetch)
		virtual void write(u16 a, u8 d) = 0;
	};
	typedef void (m6800_cpu_device::*op_func)();

	explicit m6800_cpu_device(bus_interface &bus);
	void reset() { device_reset(); }
	int run(int cycles);                              // as MAME's execute_run, for this many cycles
	void step();                                      // one instruction (or one WAI wait)
	void set_input_line(int line, int state) { execute_set_input(line, state); }

	u16 pc() const { return m_pc.w.l; }
	u16 ppc() const { return m_ppc.w.l; }
	void set_pc(u16 a) { m_pc.w.l = a; }
	u8 a() const { return m_d.b.h; }
	u8 b() const { return m_d.b.l; }
	u16 x() const { return m_x.w.l; }
	u16 sp() const { return m_s.w.l; }
	u8 cc() const { return m_cc; }
	void set_a(u8 v) { m_d.b.h = v; }
	void set_b(u8 v) { m_d.b.l = v; }
	void set_x(u16 v) { m_x.w.l = v; }
	void set_sp(u16 v) { m_s.w.l = v; }
	void set_cc(u8 v) { m_cc = u8(0xc0 | v); }   // bits 7-6 read as 1
	bool waiting() const { return m_wai_state & M6800_WAI; }
	void clear_wait() { m_wai_state &= u8(~M6800_WAI); }
	u64 total_cycles() const { return m_total; }
	bool log_illegal = false;

protected:
	enum
	{
		M6800_WAI = 8,    // set when WAI is waiting for an interrupt
		M6800_SLP = 0x10  // HD63701 only
	};

	// ---- adapters standing in for MAME's address spaces and device services ----
	struct program_t { bus_interface *b; u8 read_byte(u32 a) { return b->read(u16(a), false); } void write_byte(u32 a, u8 d) { b->write(u16(a), d); } };
	struct opcodes_t { bus_interface *b; u8 read_byte(u32 a) { return b->read(u16(a), true); } };
	void standard_irq_callback(int, u16) {}
	void debugger_instruction_hook(u32) {}
	void debugger_wait_hook() {}
	template <typename... A> void logerror(const char *f, A... a) { if (log_illegal) fprintf(stderr, f, a...); }

	bus_interface &m_bus;
	program_t m_program, m_cprogram;
	opcodes_t m_copcodes;
	u64 m_total = 0;

	void device_reset();
	void execute_run();
	virtual void execute_one();
	void execute_set_input(int inputnum, int state);

	PAIR m_ppc;         // Previous program counter
	PAIR m_pc;          // Program counter
	PAIR m_s;           // Stack pointer
	PAIR m_x;           // Index register
	PAIR m_d;           // Accumulators
	PAIR m_ea;          // effective address (temporary variable)
	u8 m_cc;            // Condition codes
	u8 m_wai_state;     // WAI opcode state (or sleep opcode state)
	u8 m_nmi_state;     // NMI line state
	u8 m_nmi_pending;   // NMI pending
	u8 m_irq_state[5];  // IRQ line state [IRQ1,TIN,IS3,..]

	const op_func *m_insn;
	const u8 *m_cycles; // clock cycle of instruction table

	int m_icount;

	static const u8 flags8i[256];
	static const u8 flags8d[256];
	static const u8 cycles_6800[256];
	static const op_func m6800_insn[256];

	u32 RM16(u32 Addr);
	void WM16(u32 Addr, PAIR *p);
	void enter_interrupt(const char *message, u16 irq_vector);
	virtual bool check_irq1_enabled();
	virtual void check_irq2() { }
	virtual void check_irq_lines();

	virtual void increment_counter(int amount);
	virtual void eat_cycles();
	virtual void cleanup_counters() { }
	virtual void take_trap() { }

""" + '\n'.join(decls) + """
};
#endif
"""

macros = between(cpp, '#define pPPC', '/* include the opcode functions */')
tables = between(cpp, '// to prevent the possibility of MAME locking up', 'const u8 m6800_cpu_device::cycles_nsc8105')
insn = between(cpp, 'const m6800_cpu_device::op_func m6800_cpu_device::m6800_insn[0x100]', 'const m6800_cpu_device::op_func m6800_cpu_device::nsc8105_insn')
routines = ''.join(function(cpp, s) for s in [
    'u32 m6800_cpu_device::RM16', 'void m6800_cpu_device::WM16', 'void m6800_cpu_device::enter_interrupt',
    'void m6800_cpu_device::check_irq_lines', 'bool m6800_cpu_device::check_irq1_enabled',
    'void m6800_cpu_device::increment_counter', 'void m6800_cpu_device::eat_cycles',
    'void m6800_cpu_device::device_reset', 'void m6800_cpu_device::execute_set_input',
    'void m6800_cpu_device::execute_run', 'void m6800_cpu_device::execute_one'])

body = LICENSE + NOTE + """#include "cpu/m6800/m6800.h"
#include <algorithm>
#include <iterator>

#define LOGIRQ(...) do { } while (0)   // [port] logmacro.h

""" + macros + """/* include the opcode functions */
#include "6800ops.hxx"

""" + tables + "#undef XX // /illegal opcode unknown cc\n\n" + insn + """
// [port] device_start: the initial state MAME's device_start sets up
m6800_cpu_device::m6800_cpu_device(bus_interface &bus)
	: m_bus(bus), m_insn(m6800_insn), m_cycles(cycles_6800)
{
	m_program.b = m_cprogram.b = m_copcodes.b = &bus;
	m_ppc.d = 0;
	m_pc.d = 0;
	m_s.d = 0;
	m_x.d = 0;
	m_d.d = 0;
	m_ea.d = 0;
	m_cc = 0;
	m_wai_state = 0;
	m_nmi_state = 0;
	m_nmi_pending = 0;
	std::fill(std::begin(m_irq_state), std::end(m_irq_state), 0);
	m_icount = 0;
}

""" + routines + """
// [port] the scheduler's part: run for a number of cycles, or a single instruction
int m6800_cpu_device::run(int cycles)
{
	m_icount = cycles;
	execute_run();
	const int used = cycles - m_icount;
	m_total += u64(used);
	return used;
}

void m6800_cpu_device::step()
{
	m_icount = 0;
	check_irq_lines();
	if (m_wai_state & (M6800_WAI | M6800_SLP))
		increment_counter(1);
	else
		execute_one();
	m_total += u64(-m_icount);
}
"""

os.makedirs(dst, exist_ok=True)
open(os.path.join(dst, 'm6800.h'), 'w').write(header)
open(os.path.join(dst, 'm6800.cpp'), 'w').write(body)
open(os.path.join(dst, '6800ops.hxx'), 'w').write(ops)
print('wrote', os.path.join(dst, 'm6800.h'), 'm6800.cpp', '6800ops.hxx')
